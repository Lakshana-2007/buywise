"""
LangGraph pipeline state.

`FinancialState` is the typed dict that flows through every node in the
LangGraph workflow.  Every field is optional at construction time and
gets populated as the pipeline progresses.

Design principles:
- Immutable inputs (request, profile) are set once and never changed.
- Computed fields are set by specific nodes and must not be touched by others.
- The validator_passed flag gates the ranking step.
- replan_count prevents infinite replan loops.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Any, Optional, TYPE_CHECKING

if TYPE_CHECKING:
    from buywise.data.joins import RequestContext
    from buywise.data.evidence import EvidenceGraph
    from buywise.core.models import FinancialEvent, OutputRow


# ── Spending change representation ────────────────────────────────────────────

@dataclass
class SpendingChange:
    """A single permitted flexible expense modification."""
    action: str          # "stop" | "reduce_to"
    event_id: str
    new_amount: Optional[float] = None  # Only for reduce_to

    def to_string(self) -> str:
        if self.action == "stop":
            return f"stop:{self.event_id}"
        elif self.action == "reduce_to" and self.new_amount is not None:
            return f"reduce_to:{self.event_id}:{self.new_amount}"
        raise ValueError(f"Invalid spending change: action={self.action}, amount={self.new_amount}")

    @staticmethod
    def from_string(s: str) -> "SpendingChange":
        """Parse 'stop:event_id' or 'reduce_to:event_id:amount'."""
        parts = s.strip().split(":")
        if parts[0] == "stop" and len(parts) == 2:
            return SpendingChange(action="stop", event_id=parts[1])
        elif parts[0] == "reduce_to" and len(parts) == 3:
            return SpendingChange(action="reduce_to", event_id=parts[1], new_amount=float(parts[2]))
        raise ValueError(f"Cannot parse spending change: {s!r}")


# ── Payment plan entry ────────────────────────────────────────────────────────

@dataclass
class PaymentEntry:
    """One line in a payment plan."""
    payment_date: date
    amount: float

    def to_string(self) -> str:
        return f"{self.payment_date.isoformat()}:{self.amount}"


@dataclass
class PaymentPlan:
    """Ordered list of payments for a recommended strategy."""
    entries: list[PaymentEntry] = field(default_factory=list)
    payment_option_id: Optional[str] = None  # Set for installment plans

    def to_string(self) -> str:
        if not self.entries:
            return "none"
        return "|".join(e.to_string() for e in sorted(self.entries, key=lambda e: e.payment_date))

    @property
    def total_amount(self) -> float:
        return sum(e.amount for e in self.entries)

    @property
    def first_payment_date(self) -> Optional[date]:
        if not self.entries:
            return None
        return min(e.payment_date for e in self.entries)

    @property
    def last_payment_date(self) -> Optional[date]:
        if not self.entries:
            return None
        return max(e.payment_date for e in self.entries)

    @property
    def num_payments(self) -> int:
        return len(self.entries)


# ── Candidate strategy ────────────────────────────────────────────────────────

@dataclass
class CandidateStrategy:
    """
    A fully-specified payment strategy that has been generated by the
    strategy engine.  May or may not have passed the safety validator yet.
    """
    payment_method: str      # full_payment | partial_payment | installments | wait | not_recommended
    payment_plan: PaymentPlan
    spending_changes: list[SpendingChange] = field(default_factory=list)
    payment_option_id: Optional[str] = None  # For installment options

    # Set by the validator
    is_valid: bool = False
    validation_violations: list[str] = field(default_factory=list)
    minimum_projected_balance: Optional[float] = None

    # Set by the ranker
    rank: Optional[int] = None
    rank_reason: str = ""

    @property
    def completes_by(self) -> Optional[date]:
        return self.payment_plan.last_payment_date

    @property
    def total_amount_paid(self) -> float:
        return self.payment_plan.total_amount

    @property
    def num_spending_changes(self) -> int:
        return len(self.spending_changes)

    @property
    def requires_spending_changes(self) -> bool:
        return len(self.spending_changes) > 0

    def spending_changes_string(self) -> str:
        if not self.spending_changes:
            return "none"
        return "|".join(sc.to_string() for sc in self.spending_changes)

    def __repr__(self) -> str:
        return (
            f"CandidateStrategy(method={self.payment_method}, "
            f"total={self.total_amount_paid:.2f}, "
            f"changes={len(self.spending_changes)}, "
            f"valid={self.is_valid})"
        )


# ── Safety proof ─────────────────────────────────────────────────────────────

@dataclass
class SafetyProof:
    """
    Machine-generated proof that the selected strategy is financially safe.
    The LLM may explain this but must not alter its values.
    """
    requested_amount: float
    amount_safe_to_pay: float
    strategy: str
    payment_plan_string: str
    minimum_projected_balance: float
    required_minimum_balance: float
    plan_completion_date: Optional[date]
    desired_completion_date: date
    spending_changes: list[SpendingChange]

    # Individual constraint results
    minimum_balance_ok: bool = False
    completion_deadline_ok: bool = False
    payment_method_ok: bool = False
    essential_expense_ok: bool = False
    spending_change_count_ok: bool = False
    amount_bounds_ok: bool = False

    @property
    def all_constraints_pass(self) -> bool:
        return all([
            self.minimum_balance_ok,
            self.completion_deadline_ok,
            self.payment_method_ok,
            self.essential_expense_ok,
            self.spending_change_count_ok,
            self.amount_bounds_ok,
        ])

    def to_dict(self) -> dict[str, Any]:
        return {
            "requested_amount": self.requested_amount,
            "amount_safe_to_pay": self.amount_safe_to_pay,
            "strategy": self.strategy,
            "minimum_projected_balance": self.minimum_projected_balance,
            "required_minimum_balance": self.required_minimum_balance,
            "plan_completion_date": str(self.plan_completion_date) if self.plan_completion_date else None,
            "desired_completion_date": str(self.desired_completion_date),
            "checks": {
                "minimum_balance": "PASS" if self.minimum_balance_ok else "FAIL",
                "completion_deadline": "PASS" if self.completion_deadline_ok else "FAIL",
                "payment_method": "PASS" if self.payment_method_ok else "FAIL",
                "essential_expenses": "PASS" if self.essential_expense_ok else "FAIL",
                "spending_change_count": "PASS" if self.spending_change_count_ok else "FAIL",
                "amount_bounds": "PASS" if self.amount_bounds_ok else "FAIL",
            },
        }


# ── Main pipeline state ───────────────────────────────────────────────────────

@dataclass
class FinancialState:
    """
    The single state object that flows through every LangGraph node.

    Fields are populated progressively as the pipeline runs:
    1. context (set at entry)
    2. evidence_graph (set by EvidenceExtractor node)
    3. normalized_events (set by EventNormalizer node)
    4. amount_safe_to_pay + earliest_full_payment_date (set by FinancialTwin)
    5. candidate_strategies (set by StrategyGenerator)
    6. valid_strategies (set by SafetyValidator)
    7. selected_strategy (set by StrategyRanker)
    8. safety_proof (set by SafetyProofBuilder)
    9. output_row (set by ExplanationGenerator)
    """

    # ── Immutable inputs ──────────────────────────────────────────────────────
    context: "RequestContext"

    # ── Evidence extraction ───────────────────────────────────────────────────
    evidence_graph: Optional["EvidenceGraph"] = None

    # ── Normalized event list ─────────────────────────────────────────────────
    # Events after: dedup, ignore-filtering, amendment application,
    # image-amount resolution, currency conversion to home_currency
    normalized_events: list["FinancialEvent"] = field(default_factory=list)

    # ── Financial Twin outputs ────────────────────────────────────────────────
    # The most the user can safely pay on request_date (no spending changes)
    amount_safe_to_pay: float = 0.0
    # Earliest date the full requested_amount passes the 90-day safety check
    earliest_full_payment_date: Optional[date] = None
    # Daily balance projection: {date -> projected_balance}
    daily_balance_projection: dict[str, float] = field(default_factory=dict)

    # ── Strategy generation & validation ─────────────────────────────────────
    candidate_strategies: list[CandidateStrategy] = field(default_factory=list)
    valid_strategies: list[CandidateStrategy] = field(default_factory=list)

    # ── Ranking ───────────────────────────────────────────────────────────────
    selected_strategy: Optional[CandidateStrategy] = None

    # ── Proof & explanation ───────────────────────────────────────────────────
    safety_proof: Optional[SafetyProof] = None
    decision_explanation: str = ""
    explanation_fallback_used: bool = False

    # ── Pipeline control ──────────────────────────────────────────────────────
    replan_count: int = 0
    max_replans: int = 3
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    # ── Final output ──────────────────────────────────────────────────────────
    output_row: Optional["OutputRow"] = None

    @property
    def request_id(self) -> str:
        return self.context.request_id

    @property
    def user_id(self) -> str:
        return self.context.user_id

    @property
    def should_replan(self) -> bool:
        return self.replan_count < self.max_replans

    def add_error(self, msg: str) -> None:
        self.errors.append(msg)

    def add_warning(self, msg: str) -> None:
        self.warnings.append(msg)

    def is_complete(self) -> bool:
        return self.output_row is not None

    def __repr__(self) -> str:
        return (
            f"FinancialState({self.request_id}, "
            f"safe={self.amount_safe_to_pay:.2f}, "
            f"candidates={len(self.candidate_strategies)}, "
            f"valid={len(self.valid_strategies)}, "
            f"selected={self.selected_strategy.payment_method if self.selected_strategy else None})"
        )
